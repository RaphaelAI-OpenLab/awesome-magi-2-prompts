"""Repository badges and original local SVG language pills."""

from __future__ import annotations

import html
import unicodedata
from pathlib import Path
from urllib.parse import quote, urlencode

from common import ROOT, repo_url
from i18n import LANGUAGE_NAMES, LANGUAGES, filename, ui


def text_width(text: str, size: int = 12) -> int:
    """Approximate pixel width for SVG pill labels."""
    units = sum(
        0 if unicodedata.combining(ch)
        else 1.75 if unicodedata.east_asian_width(ch) in "WF"
        else 0.66
        for ch in text
    )
    return round(units * size)


def pill(text: str, color: str, *, current: bool = False, title: str | None = None) -> str:
    """Render an accessible local SVG pill badge."""
    width = max(96, text_width(text) + (49 if current else 32))
    label = html.escape(text)
    description = html.escape(title or text)
    background, foreground, border = (color, "#ffffff", color) if current else ("#f8fafc", color, "#cbd5e1")
    check = (
        f'<path d="M{width - 27} 16l4 4 8-9" fill="none" stroke="currentColor" '
        f'stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>'
        if current
        else ""
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="34" '
        f'viewBox="0 0 {width} 34" role="img" aria-label="{description}">\n'
        f"  <!-- Generated by scripts/build_readme.py; original decorative artwork. -->\n"
        f"  <title>{description}</title>"
        f'<rect x=".5" y=".5" width="{width - 1}" height="33" rx="8" fill="{background}" stroke="{border}"/>\n'
        f'  <g color="{foreground}">'
        f'<text x="16" y="22" fill="currentColor" font-family="Arial, \'Noto Sans\', sans-serif" '
        f'font-size="12" font-weight="600">{label}</text>{check}</g>\n'
        f"</svg>\n"
    )


def language_nav(language: str, *, prefix: str = "") -> str:
    """Render local SVG language navigation links."""
    links = []
    for code in LANGUAGES:
        active = code == language
        state = ui("Current language", "当前语言", language) if active else ui("View translation", "切换语言", language)
        alt = f"{state}: {LANGUAGE_NAMES[code]}"
        asset = f"{prefix}assets/badges/language-{code}" + ("-current" if active else "") + ".svg"
        links.append(
            f'<a href="{prefix}{filename(code)}"><img src="{asset}" '
            f'alt="{html.escape(alt, quote=True)}" height="34" /></a>'
        )
    return " ".join(links)


def repo_badges(config: dict, language: str) -> str:
    """Render standard GitHub repository identity badges."""
    project = config["project"]
    slug = f"{project['repository_owner']}/{project['repository_slug']}"
    repo = repo_url(config)
    workflow = f"{repo}/actions/workflows/validate.yml"
    branch_query = urlencode({"branch": project["default_branch"]})
    badges = [
        ("Awesome", "https://awesome.re/badge.svg", "https://github.com/sindresorhus/awesome"),
        (
            ui("Star on GitHub", "在 GitHub 点 Star", language),
            f"https://img.shields.io/github/stars/{quote(slug, safe='/')}?style=social",
            repo,
        ),
        (
            ui("License: MIT", "许可证: MIT", language),
            "https://img.shields.io/badge/License-MIT-lightgrey.svg",
            "LICENSE",
        ),
        (
            ui("Validation CI", "自动校验 CI", language),
            f"{workflow}/badge.svg?{branch_query}",
            workflow,
        ),
        (
            ui("PRs welcome", "欢迎贡献 PR", language),
            "https://img.shields.io/badge/PRs-welcome-brightgreen.svg",
            "CONTRIBUTING.md",
        ),
    ]
    return "\n".join(f"[![{label}]({image})]({target})" for label, image, target in badges)


def asset_outputs() -> dict[Path, str]:
    """Generate deterministic local SVG badge files."""
    result: dict[Path, str] = {}
    for code, label in LANGUAGE_NAMES.items():
        result[ROOT / f"assets/badges/language-{code}.svg"] = pill(label, "#334155", title=f"View: {label}")
        result[ROOT / f"assets/badges/language-{code}-current.svg"] = pill(
            label, "#c2410c", current=True, title=f"Current: {label}"
        )
    return result
